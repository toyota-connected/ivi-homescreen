TABLE_ORDER = [
    "[global]", "[sentry]", "[[view]]", "[view.args]", "[view.shell]",
    "[view.shell.window]", "[view.shell.window.activation_area]",
    "[view.backend]", "[view.backend.drm]", "[view.backend.lease]",
    "[view.output]", "[view.engine]", "[view.hud]",
]


def classify(key):
    if key.startswith("global."):
        return "[global]", key.split(".", 1)[1]
    if key.startswith("sentry."):
        return "[sentry]", key.split(".", 1)[1]
    if key == "bundle":
        return "[[view]]", "bundle"
    if key.startswith("args."):
        return "[view.args]", key.rsplit(".", 1)[1]
    if key.startswith("shell.window.activation_area."):
        return "[view.shell.window.activation_area]", key.rsplit(".", 1)[1]
    if key.startswith("shell.window."):
        return "[view.shell.window]", key.rsplit(".", 1)[1]
    if key.startswith("shell."):
        return "[view.shell]", key.rsplit(".", 1)[1]
    if key.startswith("backend.drm."):
        return "[view.backend.drm]", key.rsplit(".", 1)[1]
    if key.startswith("backend.lease."):
        return "[view.backend.lease]", key.rsplit(".", 1)[1]
    # Must stay last of the backend.* cases: it is the catch-all.
    if key.startswith("backend."):
        return "[view.backend]", key.rsplit(".", 1)[1]
    if key.startswith("output."):
        return "[view.output]", key.split(".", 1)[1]
    if key.startswith("engine."):
        return "[view.engine]", key.rsplit(".", 1)[1]
    if key.startswith("hud."):
        return "[view.hud]", key.rsplit(".", 1)[1]
    return "[[view]]", key


def extract():
    keys = {}
    text = CFG.read_text()
    for m in re.finditer(r'at_path\("([^"]+)"\)\s*\.\s*(is_\w+)\(\)', text):
        key, t = m.group(1), m.group(2)
        if key == "view":
            continue
        keys.setdefault(key, TYPE.get(t, t))
    # [sentry] keys (different parse style in crash_handler.cc)
    crash = CRASH.read_text()
    sentry_section = crash[crash.find('get("sentry")'):]
    for m in re.finditer(r'get\("([^"]+)"\)', sentry_section):
        k = m.group(1)
        if k == "sentry":
            continue
        keys.setdefault("sentry." + k, "string")
    # [view.output] entries are read through a table helper (ParseOutputMatch
    # reads t["<field>"]), and [[view.output]] arrays iterate the node, so the
    # at_path() scraper above can't see the leaf keys. List them here so they
    # stay in the reference table.
    for k, t in (
        ("output.name", "string"),
        ("output.wl_name", "string"),
        ("output.drm_connector", "string"),
        ("output.serial", "string"),
        ("output.index", "int"),
        ("output.preload", "bool"),
        ("output.on_disconnect", "string"),
        ("output.x", "int"),
        ("output.y", "int"),
        ("output.touch_device", "string"),
    ):
        keys.setdefault(k, t)
    return keys


def build():
    keys = extract()
    missing = sorted(k for k in keys if k not in META)
    if missing:
        sys.stderr.write(
            "error: parser keys with no META entry (update scripts/"
            "gen_config_reference.py):\n  " + "\n  ".join(missing) + "\n")
        sys.exit(2)
    stale = sorted(k for k in META if k not in keys)
    if stale:
        sys.stderr.write(
            "warning: META entries no longer parsed (remove them):\n  "
            + "\n  ".join(stale) + "\n")

    rows = {t: [] for t in TABLE_ORDER}
    for key in keys:
        table, name = classify(key)
        default, values, applies, desc = META[key]
        rows[table].append((name, keys[key], default, values, applies, desc, key))
    for t in rows:
        rows[t].sort(key=lambda r: r[6])
    return rows


def render_table(rows):
    # Escape '|' so it doesn't split the markdown table cell, and wrap the
    # type/values cells in backticks so '<...>' isn't read as HTML.
    def cell(s):
        return "`" + s.replace("|", "\\|") + "`"

    out = [
        "| table | key | type | default | values | applies to |",
        "|---|---|---|---|---|---|",
    ]
    for table in TABLE_ORDER:
        for name, typ, default, values, applies, desc, _ in rows[table]:
            out.append(f"| `{table}` | `{name}` | {cell(typ)} | {cell(default)} "
                       f"| {cell(values)} | {applies} |")
    return "\n".join(out)


def render_reftoml(rows):
    out = [
        "# config.toml — REFERENCE. Lists every key the parser reads, grouped by",
        "# table, with type / default / valid values / applies-to. This file is a",
        "# reference, NOT runnable as-is: AGL window/activation keys, ivi surface_id",
        "# and the DRM knobs are mutually exclusive by shell/backend. For runnable",
        "# configs see the other files in this directory. Generated by",
        "# scripts/gen_config_reference.py — do not edit by hand.",
        "",
    ]
    for table in TABLE_ORDER:
        if not rows[table]:
            continue
        out.append(table)
        for name, typ, default, values, applies, desc, _ in rows[table]:
            out.append(f"  # {desc}")
            out.append(f"  # type={typ} default={default} values={values} applies={applies}")
            out.append(f"  {name} =")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def capture_help():
    # The binary's --help is the source of truth for the CLI. Returns a fenced
    # code block, or None if no binary is available (skip, don't fail).
    for b in (ROOT / "cmake-build-debug/shell/homescreen",
              ROOT / "build/shell/homescreen"):
        if not b.exists():
            continue
        try:
            r = subprocess.run([str(b), "--help"], capture_output=True,
                               text=True, timeout=15)
        except Exception:
            return None
        # --help is program output on stdout; stderr carries startup log lines
        # (e.g. the DLT/sink bring-up warnings) that are not part of the CLI
        # reference, so capture stdout only.
        text = r.stdout or ""
        i = text.find("Usage:")
        if i >= 0:
            text = text[i:]
        return "```text\n" + text.strip() + "\n```"
    return None


def replace_block(text, begin, end, body):
    if begin in text and end in text:
        pre = text[: text.index(begin) + len(begin)]
        post = text[text.index(end):]
        return pre + "\n\n" + body + "\n\n" + post
    return None


def main():
    check = "--check" in sys.argv[1:]
    rows = build()
    reftoml = render_reftoml(rows)
    table = render_table(rows)

    changed = []
    if (not REFTOML.exists()) or REFTOML.read_text() != reftoml:
        changed.append(str(REFTOML.relative_to(ROOT)))

    readme = README.read_text() if README.exists() else ""
    new_readme = readme
    r = replace_block(new_readme, BEGIN, END, table)
    if r is not None:
        new_readme = r
    else:
        sys.stderr.write("note: README.md has no CONFIG-REFERENCE markers; "
                         "skipping config table.\n")
    cli = capture_help()
    if cli is None:
        sys.stderr.write("note: no homescreen binary found "
                         "(cmake-build-debug/ or build/); skipping CLI block.\n")
    else:
        r = replace_block(new_readme, BEGIN_CLI, END_CLI, cli)
        if r is not None:
            new_readme = r
        else:
            sys.stderr.write("note: README.md has no CLI-REFERENCE markers; "
                             "skipping CLI block.\n")
    if new_readme != readme:
        changed.append("README.md")

    if check:
        if changed:
            sys.stderr.write("config reference is STALE; run "
                             "scripts/gen_config_reference.py:\n  "
                             + "\n  ".join(changed) + "\n")
            sys.exit(1)
        print("config reference up to date")
        return

    REFTOML.parent.mkdir(parents=True, exist_ok=True)
    REFTOML.write_text(reftoml)
    if new_readme != readme:
        README.write_text(new_readme)
    print("wrote " + ", ".join(changed) if changed else "nothing to update")


if __name__ == "__main__":
    main()
