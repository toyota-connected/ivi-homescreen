#   docs/config-examples/reference.toml  — annotated, every key (NOT runnable)
#   README.md                            — table between the CONFIG-REFERENCE
#                                          markers (only if the markers exist)
#
# Usage:
#   scripts/gen_config_reference.py          # write the outputs
#   scripts/gen_config_reference.py --check  # exit 1 if outputs are stale (CI)

